import chalk from "chalk";
import type { ScanReport, CheckResult, CategoryScore } from "../types.js";

function scoreColor(score: number): (text: string) => string {
  if (score >= 90) return chalk.green;
  if (score >= 70) return chalk.yellow;
  return chalk.red;
}

function statusIcon(status: CheckResult["status"]): string {
  switch (status) {
    case "pass":
      return chalk.green("PASS");
    case "warn":
      return chalk.yellow("WARN");
    case "fail":
      return chalk.red("FAIL");
  }
}

function renderCategory(category: CategoryScore): string {
  const color = scoreColor(category.score);
  const lines: string[] = [];

  lines.push("");
  lines.push(`  ${chalk.bold(category.name)}  ${color(`${category.score}/100`)}`);
  lines.push(`  ${"─".repeat(40)}`);

  for (const check of category.checks) {
    lines.push(`  ${statusIcon(check.status)}  ${check.name}`);
    lines.push(`       ${chalk.dim(check.message)}`);
    if (check.details && check.details.length > 0) {
      for (const detail of check.details.slice(0, 5)) {
        lines.push(`       ${chalk.dim("→ " + detail)}`);
      }
      if (check.details.length > 5) {
        lines.push(`       ${chalk.dim(`  ...and ${check.details.length - 5} more`)}`);
      }
    }
  }

  return lines.join("\n");
}

export function renderTerminal(report: ScanReport): string {
  const color = scoreColor(report.overallScore);
  const lines: string[] = [];

  lines.push("");
  lines.push(chalk.bold("  reposcore"));
  lines.push(chalk.dim(`  ${report.repoPath}`));
  lines.push("");
  lines.push(`  Overall Score: ${color(chalk.bold(`${report.overallScore}/100`))}`);

  for (const category of report.categories) {
    lines.push(renderCategory(category));
  }

  lines.push("");
  lines.push(chalk.dim(`  Scanned in ${report.duration}ms`));
  lines.push(chalk.dim("  Generated by reposcore — graylining.com"));
  lines.push("");

  return lines.join("\n");
}
